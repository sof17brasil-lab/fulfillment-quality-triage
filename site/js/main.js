/* Every chart is built as soon as its data lands. The scroll reveal is a
   purely visual layer on top of a chart that already exists, so a chart can
   never be missing because an animation did not fire. Building eagerly costs
   one layout pass up front and removes a whole class of "the graphs are
   blank" bugs.
   The name is kept so the thirteen call sites below read unchanged. */
const pending = new Map();
const buildQueue = [];

function chartWhenVisible(canvasId, build) {
  const el = document.getElementById(canvasId);
  if (!el) return;
  buildQueue.push([canvasId, build, el]);
}

/* Hand the main thread back between frames. Building all twelve charts in one
   synchronous block made a single ~1.2s task, which is most of the Lighthouse
   Total Blocking Time: a long task blocks input, so the page feels stuck even
   though it has painted. Yielding turns one unbreakable task into twelve short
   ones without delaying anything meaningfully. */
const yieldToMain = () =>
  (window.scheduler && typeof scheduler.yield === 'function')
    ? scheduler.yield()
    : new Promise((r) => setTimeout(r, 0));

/* Still no dependency on scrolling: every queued chart is built, in page
   order, within a few hundred milliseconds of the data arriving. */
async function drainChartQueue() {
  while (buildQueue.length) {
    const [id, build, el] = buildQueue.shift();
    try {
      build(el);
    } catch (err) {
      console.error('chart failed:', id, err);
    }
    await yieldToMain();
  }
}

/* ---------- reveal + lazy chart build ---------- */
function observeReveals(ledger) {
  const items = document.querySelectorAll('.rise');
  /* Replay the chart's draw-in now that it is on screen. The chart already
     holds a complete picture, so if this never runs nothing is lost but the
     flourish. */
  const animateChartsIn = (el) => {
    /* Chart.js drives its animation with requestAnimationFrame. In a hidden
       tab that never ticks, so starting one would leave the chart stuck at
       its first frame -- blank -- instead of the complete picture it already
       holds. When we cannot animate safely, we simply don't. */
    if (REDUCED || document.visibilityState === 'hidden') return;
    el.querySelectorAll('canvas').forEach((cv) => {
      const chart = window.Chart && Chart.getChart ? Chart.getChart(cv) : null;
      if (!chart || chart.$didIntro) return;
      chart.$didIntro = true;
      chart.options.animation = { duration: 700, easing: 'easeOutCubic' };
      chart.update();
    });
  };

  const fire = (el) => {
    el.classList.add('is-in');
    el.querySelectorAll('[data-count]').forEach((n) => {
      if (n.dataset.counted) return;
      n.dataset.counted = '1';
      const row = ledger[n.dataset.ledger];
      if (row) countUp(n, row);
    });
    animateChartsIn(el);
  };
  if (!('IntersectionObserver' in window)) { items.forEach(fire); return; }
  const io = new IntersectionObserver((entries) => {
    entries.forEach((e) => {
      if (!e.isIntersecting) return;
      fire(e.target);
      io.unobserve(e.target);
    });
  }, { rootMargin: '0px 0px -10% 0px', threshold: 0.12 });
  items.forEach((el) => io.observe(el));

  /* Geometry fallback. IntersectionObserver does not deliver callbacks while
     the document is hidden, so a page restored from a background tab (or
     driven headlessly) could otherwise sit at opacity 0 with its charts
     never built.

     Measuring on every scroll event forces a synchronous layout per event and
     visibly janks the page, so the work is coalesced into one rAF per frame
     and the listeners detach the moment everything has been revealed. */
  let queued = false;
  let remaining = items.length;

  const inView = (el) => {
    const r = el.getBoundingClientRect();
    return r.top < window.innerHeight * 0.92 && r.bottom > 0;
  };

  const detach = () => {
    window.removeEventListener('scroll', onScroll);
    window.removeEventListener('resize', onScroll);
    document.removeEventListener('visibilitychange', onScroll);
  };

  const sweep = () => {
    queued = false;
    items.forEach((el) => {
      if (el.classList.contains('is-in')) return;
      if (inView(el)) { fire(el); io.unobserve(el); remaining--; }
    });
    if (remaining <= 0) detach();
  };

  function onScroll() {
    if (queued) return;
    // requestAnimationFrame never fires while the document is hidden, so a
    // hidden page would queue a sweep that never runs -- exactly the case this
    // fallback exists for. Measure directly there; coalesce when visible,
    // which is the only time smoothness matters.
    if (document.visibilityState === 'hidden') { sweep(); return; }
    queued = true;
    requestAnimationFrame(sweep);
  }

  window.addEventListener('scroll', onScroll, { passive: true });
  window.addEventListener('resize', onScroll, { passive: true });
  document.addEventListener('visibilitychange', onScroll);
  remaining = items.length;
  sweep();

  /* Last line of defence. An instant jump to an anchor, a restored scroll
     position, or any browser quirk can move an element past the viewport
     between two observer samples, and it would then stay at opacity 0 for
     good. After a few seconds, show anything still hidden. Content being
     visible always beats content being animated. */
  setTimeout(() => {
    items.forEach((el) => { if (!el.classList.contains('is-in')) fire(el); });
    detach();
  }, 3000);
}

