function waffle(base) {
  const host = document.getElementById('waffle');
  const leg = document.getElementById('waffle-legend');
  if (!host) return;
  const total = base.orders;
  const parts = [
    { k: 'On time',   n: base.delivered_on_time, c: C.ok },
    { k: 'Late',      n: base.delivered_late,    c: C.warn },
    { k: 'Stalled',   n: base.stalled,           c: C.bad },
    { k: 'Cancelled', n: base.cancelled,         c: C.ember },
  ];
  // largest-remainder so the squares always total exactly 100
  const raw = parts.map((p) => (p.n / total) * 100);
  const sq = raw.map(Math.floor);
  let left = 100 - sq.reduce((a, b) => a + b, 0);
  raw.map((v, i) => [v - sq[i], i]).sort((a, b) => b[0] - a[0])
     .forEach(([, i]) => { if (left > 0) { sq[i]++; left--; } });

  const frag = document.createDocumentFragment();
  parts.forEach((p, i) => {
    for (let j = 0; j < sq[i]; j++) {
      const cell = document.createElement('i');
      cell.style.setProperty('--c', p.c);
      cell.title = `${p.k} — ${(raw[i]).toFixed(1)}% (${n0(p.n)} orders)`;
      frag.appendChild(cell);
    }
  });
  host.appendChild(frag);

  parts.forEach((p, i) => {
    const li = document.createElement('li');
    li.innerHTML = `<i></i><span></span>`;
    li.firstChild.style.setProperty('--c', p.c);
    li.lastChild.innerHTML = `${p.k} <b>${raw[i].toFixed(1)}%</b>`;
    leg.appendChild(li);
  });
}

