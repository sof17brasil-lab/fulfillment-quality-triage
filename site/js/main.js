/* ---------- formatting ---------- */
/* Take the number of decimals from the ledger value itself rather than forcing
   a fixed width. Rounding everything to 1dp printed 0.39% as "0.4%", directly
   under a caption explaining why it is not 0.37% — and SQL's round() leaves
   whole numbers looking like "231.0", which should read as 231. */
function formatterFor(row) {
  const v = String(row.value);
  if (row.unit === 'p') return () => 'p = ' + v;

  const m = v.match(/^-?\d+(?:\.(\d+))?$/);
  if (!m) return () => v;                      // already a formatted string

  const exact = Number(v);
  const dp = m[1] ? m[1].length : 0;

  /* A measurement keeps the precision the ledger recorded, so 21.0% sits
     beside 42.2% at the same width instead of collapsing to "21%". A count
     does not: SQL's round() hands back "231.0" for 231 whole orders, and
     "231.0 orders" would be nonsense. */
  const COUNTS = new Set(['orders', 'sellers', 'customers', 'weeks']);
  const places = COUNTS.has(row.unit)
    ? ((dp && exact % 1 !== 0) ? dp : 0)
    : dp;
  const fmt = (n) => Number(n).toLocaleString('en-US', {
    minimumFractionDigits: places, maximumFractionDigits: places,
  });

  // 'pp' is a difference between two percentages, so it carries its own unit.
  // 'days' deliberately does not: those values are read inline in sentences
  // that already supply the word.
  if (row.unit === '%') return (n) => fmt(n) + '%';
  if (row.unit === 'pp') return (n) => fmt(n) + 'pp';
  return fmt;
}
const renderLedgerValue = (row) => formatterFor(row)(row.value);
const n0 = (v) => Math.round(v).toLocaleString('en-US');

/* ---------- count up ---------- */
function countUp(el, row, duration = 900) {
  const format = formatterFor(row);
  const target = Number(row.value);
  const land = () => { el.textContent = renderLedgerValue(row); };
  /* A background tab never fires requestAnimationFrame, so a counted number
     would sit blank for as long as the tab stays hidden. Anything that cannot
     animate is shown at its final value instead. */
  if (REDUCED || !isFinite(target) || document.visibilityState === 'hidden') { land(); return; }
  setTimeout(land, duration + 300);   // failsafe: always reach the real value
  const started = performance.now();
  const ease = (t) => 1 - Math.pow(1 - t, 3);
  (function frame(now) {
    const t = Math.min(1, ((now || started) - started) / duration);
    if (t < 1) { el.textContent = format(target * ease(t)); requestAnimationFrame(frame); }
    else { el.textContent = renderLedgerValue(row); }
  })(started);
}

/* ---------- Chart.js defaults ---------- */
function setChartDefaults() {
  const F = Chart.defaults;
  F.font.family = "'Inter Tight', system-ui, sans-serif";
  F.font.size = 13;
  F.color = C.mute;
  F.borderColor = C.grid;
  /* Charts are built complete, with animation off, so the canvas holds a
     finished picture the instant it is constructed and never depends on an
     animation frame to exist. The draw-in is re-applied per chart when its
     card is revealed (see animateChartsIn), which is also when it is actually
     worth watching. */
  F.animation = false;
  F.maintainAspectRatio = false;
  F.plugins.legend.display = false;
  F.plugins.tooltip.backgroundColor = '#1b150d';
  F.plugins.tooltip.borderColor = 'rgba(245,228,199,0.25)';
  F.plugins.tooltip.borderWidth = 1;
  F.plugins.tooltip.titleColor = C.cream;
  F.plugins.tooltip.bodyColor = C.cream;
  F.plugins.tooltip.padding = 10;
  F.plugins.tooltip.displayColors = false;

  /* Tooltips follow the cursor instead of snapping to the data point. The
     default 'average' positioner makes the tooltip jump between marks, which
     reads as machinery; tracking the pointer keeps attention where the eye
     already is. Falls back silently if the Tooltip plugin is unavailable. */
  if (Chart.registry && Chart.registry.plugins) {
    const tip = Chart.registry.getPlugin('tooltip');
    if (tip && tip.positioners) {
      tip.positioners.cursor = function (items, pos) {
        if (!pos) return false;
        return { x: pos.x, y: pos.y - 12 };   // sit just above the pointer
      };
      F.plugins.tooltip.position = 'cursor';
    }
  }
  /* Hovering anywhere along a column reports that column, so a thin bar or a
     single line point does not demand pixel-accurate aiming. */
  F.interaction.mode = 'index';
  F.interaction.intersect = false;
  F.plugins.tooltip.animation = { duration: 140 };
}

