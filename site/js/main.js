/* ---------- hero: word-by-word reveal ----------
   Runs on load rather than on scroll: the headline is the first thing a
   hiring manager reads and it must not wait for a gesture. Each word is
   wrapped in a span and given a staggered delay; the last word starts well
   inside 2 seconds. The <em> around "weren't the seller's fault" survives the
   split, so the accent colour lands on exactly that phrase.
   If this never runs, the headline is already plain readable text. */
function splitHeadline() {
  const h = document.querySelector('[data-words]');
  if (!h) return;
  const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  let i = 0;
  const STEP = 55;         // ms between words
  const wrap = (node, accent) => {
    const frag = document.createDocumentFragment();
    node.textContent.split(/(\s+)/).forEach((tok) => {
      if (!tok.trim()) { frag.appendChild(document.createTextNode(tok)); return; }
      const w = document.createElement('span');
      w.className = 'w' + (accent ? ' w--accent' : '');
      w.textContent = tok;
      w.style.setProperty('--wd', (i++ * STEP) + 'ms');
      frag.appendChild(w);
    });
    return frag;
  };

  // walk a static copy of the child list, since we replace nodes as we go
  [...h.childNodes].forEach((node) => {
    if (node.nodeType === 3) {
      if (node.textContent.trim()) h.replaceChild(wrap(node, false), node);
    } else if (node.tagName === 'EM') {
      const inner = wrap(node.firstChild, true);
      node.replaceChild(inner, node.firstChild);
    }
  });

  /* The words are plain visible text until we are certain we can animate
     them back in. CSS transitions do not advance in a background tab, so
     hiding first and transitioning to visible would strand the headline at
     opacity 0 for anyone who opened the page in a background tab. */
  const run = () => {
    h.classList.add('words-run');
    // forces a style flush so the transition has a start value to run FROM
    void h.offsetWidth;
    h.classList.add('words-ready');
  };

  if (reduced) return;                       // words already visible, no motion
  if (document.visibilityState === 'visible') { run(); return; }

  // opened in a background tab: readable now, animated if it is ever looked at
  document.addEventListener('visibilitychange', function once() {
    if (document.visibilityState !== 'visible') return;
    document.removeEventListener('visibilitychange', once);
    run();
  });
}
document.addEventListener('DOMContentLoaded', splitHeadline);

const DATA = 'data/';
/* These files are regenerated by scripts/build_site.py whenever the analysis is
   rerun, and a stale copy would silently put the wrong numbers on the page.
   BUILD is stamped per page load and used as a query key: cache:'no-store'
   alone is not always honoured, and a cached ledger from an earlier build has
   already been observed arriving truncated. Correctness beats a cache hit on
   files this small. */
const BUILD = Date.now();

async function json(name, attempt = 0) {
  const r = await fetch(`${DATA}${name}.json?v=${BUILD}.${attempt}`, { cache: 'no-store' });
  if (!r.ok) throw new Error(`could not load ${name} (HTTP ${r.status})`);
  const t = await r.text();
  try {
    return JSON.parse(t);
  } catch {
    // A response can arrive truncated when many requests are in flight at
    // once. One retry costs nothing and turns a dead page into a loaded one.
    if (attempt < 2) return json(name, attempt + 1);
    throw new Error(`${name} arrived incomplete (${t.length} bytes) after ${attempt + 1} attempts`);
  }
}

/* Fetch in small batches rather than all at once. A dozen parallel requests is
   enough to make some static servers hand back a truncated body, and these
   files are small enough that the serial cost is irrelevant. */
async function jsonAll(names, width = 3) {
  const out = {};
  for (let i = 0; i < names.length; i += width) {
    const slice = names.slice(i, i + width);
    const got = await Promise.all(slice.map((n) => json(n)));
    slice.forEach((n, j) => { out[n] = got[j]; });
  }
  return out;
}

