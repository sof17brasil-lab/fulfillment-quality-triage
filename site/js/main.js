function sellerTable(rows, onFilter) {
  const tbody = document.querySelector('#t-sellers tbody');
  const head = document.querySelectorAll('#t-sellers th');
  const empty = document.getElementById('t-empty');
  const fSeller = document.getElementById('f-seller');
  const fState = document.getElementById('f-state');
  const fFlag = document.getElementById('f-flagged');
  const fReset = document.getElementById('f-reset');
  const max = Math.max(...rows.map((r) => r.late_handoff_pct));
  let key = 'late_handoff_pct', dir = -1;
  let data = [];

  // state list comes from the data, so it can never offer an empty option
  if (fState) {
    [...new Set(rows.map((r) => r.seller_state))].sort().forEach((st) => {
      const o = document.createElement('option');
      o.value = o.textContent = st;
      fState.appendChild(o);
    });
  }

  function apply() {
    const q = (fSeller && fSeller.value.trim().toLowerCase()) || '';
    const st = (fState && fState.value) || '';
    const flaggedOnly = fFlag ? fFlag.checked : true;
    data = rows.filter((r) =>
      (!flaggedOnly || r.is_flagged) &&
      (!st || r.seller_state === st) &&
      (!q || r.seller.toLowerCase().includes(q)));
    if (empty) empty.hidden = data.length > 0;
    if (onFilter) onFilter(data);
    draw();
  }

  function draw() {
    data.sort((a, b) => {
      const x = a[key], y = b[key];
      return (typeof x === 'string' ? x.localeCompare(y) : x - y) * dir;
    });
    tbody.replaceChildren();
    data.forEach((r) => {
      const tr = document.createElement('tr');
      tr.innerHTML = `
        <td class="is-text"></td><td class="is-text"></td><td></td><td></td>
        <td><span class="v"></span><span class="bar"><i></i></span></td><td></td><td></td>`;
      const c = tr.children;
      c[0].textContent = r.seller;
      c[1].textContent = r.seller_state;
      c[2].textContent = n0(r.orders);
      c[3].textContent = n0(r.late_handoffs);
      c[4].querySelector('.v').textContent = r.late_handoff_pct + '%';
      c[4].querySelector('i').style.width = (r.late_handoff_pct / max * 100) + '%';
      c[5].textContent = r.late_delivery_pct + '%';
      c[6].textContent = (r.low_review_pct == null ? '—' : r.low_review_pct + '%');
      tbody.appendChild(tr);
    });
    head.forEach((th) => {
      if (th.dataset.sort === key) th.setAttribute('aria-sort', dir === 1 ? 'ascending' : 'descending');
      else th.removeAttribute('aria-sort');
    });
  }

  const sortBy = (th) => {
    const k = th.dataset.sort;
    if (!k) return;
    if (k === key) dir = -dir; else { key = k; dir = th.classList.contains('is-text') ? 1 : -1; }
    draw();
  };
  head.forEach((th) => {
    th.addEventListener('click', () => sortBy(th));
    // sorting has to be reachable without a mouse
    th.addEventListener('keydown', (e) => {
      if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); sortBy(th); }
    });
  });

  [fSeller, fState, fFlag].forEach((el) => {
    if (el) el.addEventListener('input', apply);
  });
  if (fReset) fReset.addEventListener('click', () => {
    if (fSeller) fSeller.value = '';
    if (fState) fState.value = '';
    if (fFlag) fFlag.checked = true;
    apply();
  });

  apply();
}

/* The strip above the panel reports whatever the filter currently selects, so
   the summary and the table can never disagree. These are counts of the rows
   on screen, not ledger claims, which is why they carry no ledger id. */
function panelStats(rows) {
  const el = document.getElementById('panel-stats');
  if (!el) return;
  const orders = rows.reduce((s, r) => s + r.orders, 0);
  const late = rows.reduce((s, r) => s + r.late_handoffs, 0);
  const worst = rows.reduce((m, r) => Math.max(m, r.late_handoff_pct), 0);
  const cells = [
    [n0(rows.length), 'sellers shown'],
    [n0(orders), 'orders they ship'],
    [n0(late), 'late handoffs'],
    [rows.length ? worst.toFixed(1) + '%' : '—', 'worst handoff rate'],
  ];
  el.replaceChildren(...cells.map(([v, l]) => {
    const li = document.createElement('li');
    const b = document.createElement('b'); b.textContent = v;
    const s = document.createElement('span'); s.textContent = l;
    li.append(b, s);
    return li;
  }));
}

/* ---------- calculator ---------- */
function calculator() {
  const get = (id) => document.getElementById(id);
  const inputs = ['ci-orders', 'ci-pp', 'ci-cost'].map(get);
  const outD = get('co-defects'), outV = get('co-value');
  if (!inputs[0]) return;
  function run() {
    const [o, pp, cost] = inputs.map((i) => parseFloat(i.value));
    if (!isFinite(o) || !isFinite(pp) || o <= 0 || pp <= 0) {
      outD.textContent = '—'; outV.textContent = '—'; return;
    }
    const defects = o * (pp / 100);
    outD.textContent = n0(defects);
    outV.textContent = isFinite(cost) && cost > 0
      ? '$' + n0(defects * cost) : '—';
  }
  inputs.forEach((i) => i.addEventListener('input', run));
}

/* ============================ boot ============================ */
async function boot() {
  const d = await jsonAll([
    'numbers_ledger', 'public_facts',
    '02_baseline_scorecard', '03_customer_impact', '05_root_cause',
    '08_repeat_purchase', '10_initiative_sizing', '11_launch_scorecard',
    '13_dashboard_cube', '15_cancellation_trend', '16_order_timeline',
    '17_escalation',
  ]);
  const ledgerRows = d.numbers_ledger;
  const facts = d.public_facts || [];
  const base = d['02_baseline_scorecard'];
  const impact = d['03_customer_impact'];
  const root = d['05_root_cause'];
  const repeat = d['08_repeat_purchase'];
  const sizing = d['10_initiative_sizing'];
  const launch = d['11_launch_scorecard'];
  const cube = d['13_dashboard_cube'];
  const cancel = d['15_cancellation_trend'];
  const timeline = d['16_order_timeline'];
  const esc = d['17_escalation'];

  const ledger = Object.fromEntries(ledgerRows.map((r) => [r.id, r]));

  document.querySelectorAll('[data-ledger]').forEach((el) => {
    const row = ledger[el.dataset.ledger];
    if (!row) { console.warn('ledger id not found:', el.dataset.ledger); return; }
    el.title = row.claim;
    /* A stat card shows its change with a sign. The direction lives on the
       card, not in the ledger, because the ledger stores the magnitude of the
       gap and the card decides whether that gap reads as up or down. */
    if ('signed' in el.dataset) {
      const dir = el.closest('[data-dir]');
      const sign = dir && dir.dataset.dir === 'down' ? '−' : '+';
      el.textContent = sign + renderLedgerValue(row);
      return;
    }
    if (!('count' in el.dataset)) el.textContent = renderLedgerValue(row);
  });

  // the escalation seller's id and state are data, not ledger numbers
  const sellerRow = esc[0][0];
  document.querySelectorAll('[data-json="esc.seller"]').forEach((e) => e.textContent = sellerRow.seller);
  document.querySelectorAll('[data-json="esc.state"]').forEach((e) => e.textContent = sellerRow.seller_state);

  renderPublicFacts(facts);
  setChartDefaults();

  waffle(base[0][0]);
  chartCancel(cancel[0]);
  chartMonitor(cube[0]);
  chartTimeline(timeline[0]);
  chartCause(root[1]);
  chartState(root[2]);
  chartCliff(impact[1]);
  chartRepeat(repeat[1], repeat[2]);
  chartEscSeller(esc[1], sellerRow.platform_late_handoff_pct);
  chartEscRJ(esc[3]);
  chartLaunch(launch[0]);
  chartFixes(sizing[5]);
  chartSellers(cube[4]);
  // the table owns the filter; the scatter and the summary strip follow it
  sellerTable(cube[4], (selected) => { panelStats(selected); highlightSellers(selected); });
  calculator();

  // charts are queued above; build them now, yielding between each
  await drainChartQueue();

  observeReveals(ledger);
  document.documentElement.dataset.ready = 'true';
}

boot().catch((err) => {
  console.error(err);
  document.documentElement.dataset.ready = 'error';
});
